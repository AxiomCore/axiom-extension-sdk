"""Integer money and percentage helpers, equivalent to the Rust SDK primitives
`Cents` and `Percentage` (rust/sdk/src/primitives.rs).

The shared vectors in validation/x7e-money-vectors.json are generated by the
Rust code and replayed by python/tests/test_money.py.

Representation: Python ints are exact, so `Cents` covers the full Rust range
0..=2**64-1 and `Percentage` holds whole basis points 0..=10000. Arithmetic is
integer only. `Percentage.of` truncates like Rust's u64 division. Overflow and
negative results raise `ValueError` with the Rust `SdkError` message. They
never wrap. Wrong types (including `bool` and `float`) raise `TypeError`.

The module stays inside the Python AOT profile: no floats, imports or
dataclasses, only plain classes, ints and f-strings.
"""

U64_MAX = (1 << 64) - 1
U16_MAX = (1 << 16) - 1


def _integer(value: object, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{what} must be an integer")
    return int(value)


def _unsigned64(value: object, what: str) -> int:
    exact = _integer(value, what)
    if exact < 0 or exact > U64_MAX:
        raise ValueError(f"{what} must be between 0 and 18446744073709551615")
    return exact


def _decode_unsigned(value: object, maximum: int) -> int:
    """Rust `u64::decode` / `u16::decode` for an already decoded plain value."""
    if isinstance(value, bool):
        raise TypeError("expected unsigned integer, received boolean")
    if not isinstance(value, int):
        kind = "null" if value is None else "string" if isinstance(value, str) else "bytes" if isinstance(value, (bytes, bytearray)) else "list" if isinstance(value, list) else "record" if isinstance(value, dict) else type(value).__name__
        raise TypeError(f"expected unsigned integer, received {kind}")
    if value < 0:
        raise TypeError("expected unsigned integer, received signed integer")
    if value > maximum:
        raise ValueError("unsigned integer is out of range")
    return int(value)


class Cents:
    """Whole number of cents, 0..=2**64-1. Immutable, hashable, ordered."""

    __slots__ = ("_cents",)
    _cents: int
    ZERO: "Cents"

    def __init__(self, value: int) -> None:
        object.__setattr__(self, "_cents", _unsigned64(value, "Cents value"))

    def __setattr__(self, name: str, value: object) -> None:
        raise AttributeError("Cents is immutable")

    @classmethod
    def new(cls, value: int) -> "Cents":
        """Rust `Cents::new`."""
        return cls(value)

    @classmethod
    def from_dollars(cls, dollars: int) -> "Cents":
        """Rust `Cents::from_dollars`: whole dollars times 100, checked."""
        cents = _unsigned64(dollars, "dollar amount") * 100
        if cents > U64_MAX:
            raise ValueError("dollar amount exceeds Cents range")
        return cls(cents)

    @classmethod
    def decode(cls, value: object) -> "Cents":
        """Rust `Cents::decode` for a value decoded by the SDK bridge."""
        return cls(_decode_unsigned(value, U64_MAX))

    @property
    def value(self) -> int:
        return self._cents

    def encode(self) -> int:
        return self._cents

    def min(self, other: "Cents") -> "Cents":
        return self if self._cents <= other._cents else other

    def checked_sub(self, other: "Cents") -> "Cents":
        """Rust `Cents::checked_sub`: never negative."""
        if other._cents > self._cents:
            raise ValueError("currency subtraction would be negative")
        return Cents(self._cents - other._cents)

    def as_currency(self) -> str:
        """`$<dollars>.<cents>`, for example `$1234.56`."""
        cents = self._cents % 100
        return f"${self._cents // 100}.{'0' if cents < 10 else ''}{cents}"

    def as_saving(self) -> str:
        """A saving: U+2212 MINUS SIGN before the currency text."""
        return "−" + self.as_currency()

    def __eq__(self, other: object) -> bool:
        return isinstance(other, Cents) and self._cents == other._cents

    def __hash__(self) -> int:
        return hash(("Cents", self._cents))

    def __lt__(self, other: "Cents") -> bool:
        return self._cents < other._cents

    def __le__(self, other: "Cents") -> bool:
        return self._cents <= other._cents

    def __gt__(self, other: "Cents") -> bool:
        return self._cents > other._cents

    def __ge__(self, other: "Cents") -> bool:
        return self._cents >= other._cents

    def __repr__(self) -> str:
        return f"Cents({self._cents})"

    def __str__(self) -> str:
        return self.as_currency()


Cents.ZERO = Cents(0)


class Percentage:
    """A percentage in whole basis points, 0..=10000. Immutable, hashable, ordered."""

    __slots__ = ("_basis_points",)
    _basis_points: int

    def __init__(self, basis_points: int) -> None:
        exact = _integer(basis_points, "basis points")
        if exact < 0 or exact > 10_000:
            raise ValueError("basis points must be between 0 and 10000")
        object.__setattr__(self, "_basis_points", exact)

    def __setattr__(self, name: str, value: object) -> None:
        raise AttributeError("Percentage is immutable")

    @classmethod
    def from_whole(cls, value: int) -> "Percentage":
        """Rust `Percentage::from_whole`: 0 to 100 percent."""
        exact = _integer(value, "percentage")
        if exact < 0 or exact > 100:
            raise ValueError("percentage must be between 0 and 100")
        return cls(exact * 100)

    @classmethod
    def from_basis_points(cls, value: int) -> "Percentage":
        """Rust `Percentage::from_basis_points`: 0 to 10000."""
        return cls(value)

    @classmethod
    def decode(cls, value: object) -> "Percentage":
        """Rust `Percentage::decode`: a u16, then the basis-point range."""
        return cls(_decode_unsigned(value, U16_MAX))

    @property
    def basis_points(self) -> int:
        return self._basis_points

    def of(self, amount: Cents) -> Cents:
        """Rust `Percentage::of`: amount * basis_points // 10000. Like Rust, it
        raises when the intermediate product exceeds 2**64-1, even if the
        quotient would fit."""
        product = amount.value * self._basis_points
        if product > U64_MAX:
            raise ValueError("percentage calculation overflowed")
        return Cents(product // 10_000)

    def encode(self) -> int:
        return self._basis_points

    def __eq__(self, other: object) -> bool:
        return isinstance(other, Percentage) and self._basis_points == other._basis_points

    def __hash__(self) -> int:
        return hash(("Percentage", self._basis_points))

    def __lt__(self, other: "Percentage") -> bool:
        return self._basis_points < other._basis_points

    def __le__(self, other: "Percentage") -> bool:
        return self._basis_points <= other._basis_points

    def __gt__(self, other: "Percentage") -> bool:
        return self._basis_points > other._basis_points

    def __ge__(self, other: "Percentage") -> bool:
        return self._basis_points >= other._basis_points

    def __repr__(self) -> str:
        return f"Percentage(basis_points={self._basis_points})"


__all__ = ["Cents", "Percentage"]
